"""
Generates app/sdk/roguelike/roguelikeCardTags.js from the `tags` column of roguelike_csv/cards_*.csv.
Tags are ;-separated, lowercased. Run after editing the CSVs: python scripts/roguelike_card_tags.py
"""
import csv, glob, io, json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'app', 'sdk', 'roguelike', 'roguelikeCardTags.js')

def read_csv(path):
    raw = open(path, 'rb').read()
    try:
        text = raw.decode('utf-8-sig')
    except UnicodeDecodeError:
        # saved by Excel
        text = raw.decode('cp1252')
    return list(csv.DictReader(io.StringIO(text, newline='')))

tags_by_card_id = {}
for path in sorted(glob.glob(os.path.join(ROOT, 'roguelike_csv', 'cards_*.csv'))):
    for row in read_csv(path):
        tags = sorted(set(t.strip().lower() for t in (row.get('tags') or '').split(';') if t.strip()))
        if tags:
            tags_by_card_id[int(row['id'])] = tags

lines = ['  %d: %s,' % (card_id, json.dumps(tags_by_card_id[card_id]).replace('"', "'")) for card_id in sorted(tags_by_card_id)]
js = """// GENERATED by scripts/roguelike_card_tags.py from the `tags` column of roguelike_csv/cards_*.csv, do not edit by hand.
const RoguelikeCardTags = {};

RoguelikeCardTags.tagsByCardId = {
%s
};

/**
 * Returns the tags of a card.
 * @param {Number} cardId
 * @returns {Array}
 */
RoguelikeCardTags.getTags = function (cardId) {
  return RoguelikeCardTags.tagsByCardId[cardId] || [];
};

/**
 * Returns whether a card has a tag.
 * @param {Number} cardId
 * @param {String} tag
 * @returns {Boolean}
 */
RoguelikeCardTags.hasTag = function (cardId, tag) {
  return RoguelikeCardTags.getTags(cardId).indexOf(tag) !== -1;
};

module.exports = RoguelikeCardTags;
""" % '\n'.join(lines)
open(OUT, 'w', encoding='utf-8', newline='\n').write(js)
print('%d tagged cards -> %s' % (len(tags_by_card_id), OUT))

"""
Generates app/sdk/roguelike/roguelikeProgressionData.js from the progression design tables:
- roguelike_csv/account_progression.csv: global levels (level,xp,unlock,value,description)
- roguelike_csv/general_progression.csv: hero levels, shared by every general (level,xp,unlock,value,description)
- roguelike_csv/progression_xp.csv: xp earned by fight (source,xp,description)
- the `mods` column of roguelike_csv/generals/*.csv: starting deck mods unlocked by hero level,
  ;-separated `mod_id@level` (a mod without @level is always unlocked)
Run after editing the CSVs: python scripts/roguelike_progression.py
"""
import csv, glob, io, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV_DIR = os.path.join(ROOT, 'roguelike_csv')
OUT = os.path.join(ROOT, 'app', 'sdk', 'roguelike', 'roguelikeProgressionData.js')

def read_csv(path):
    raw = open(path, 'rb').read()
    try:
        text = raw.decode('utf-8-sig')
    except UnicodeDecodeError:
        # saved by Excel
        text = raw.decode('cp1252')
    return list(csv.DictReader(io.StringIO(text, newline='')))

def to_number(value):
    value = (value or '').strip()
    if value == '':
        return 0
    number = float(value)
    return int(number) if number.is_integer() else number

def read_levels(path):
    levels = {}
    for row in read_csv(path):
        if not (row.get('level') or '').strip():
            continue
        level = int(row['level'])
        entry = levels.setdefault(level, {'level': level, 'xp': None, 'unlocks': []})
        if (row.get('xp') or '').strip():
            entry['xp'] = to_number(row['xp'])
        unlock = (row.get('unlock') or '').strip().lower()
        if unlock:
            entry['unlocks'].append({'unlock': unlock, 'value': to_number(row.get('value')), 'description': (row.get('description') or '').strip()})
    result = []
    for level in sorted(levels):
        entry = levels[level]
        if entry['xp'] is None:
            sys.exit('%s: level %d has no xp' % (path, level))
        result.append(entry)
    for previous, entry in zip(result, result[1:]):
        if entry['xp'] <= previous['xp']:
            sys.exit('%s: level %d needs more xp than level %d' % (path, entry['level'], previous['level']))
    return result

account_levels = read_levels(os.path.join(CSV_DIR, 'account_progression.csv'))
general_levels = read_levels(os.path.join(CSV_DIR, 'general_progression.csv'))
xp = {row['source'].strip().lower(): to_number(row['xp']) for row in read_csv(os.path.join(CSV_DIR, 'progression_xp.csv')) if (row.get('source') or '').strip()}

starting_card_mods = {}
for path in sorted(glob.glob(os.path.join(CSV_DIR, 'generals', '*.csv'))):
    rows = read_csv(path)
    general_rows = [row for row in rows if row['role'] == 'general']
    if not general_rows:
        continue
    general_id = int(general_rows[0]['id'])
    for row in rows:
        if row['role'] != 'card':
            continue
        mods = []
        for entry in (row.get('mods') or '').split(';'):
            entry = entry.strip()
            if not entry:
                continue
            mod_id, _, level = entry.partition('@')
            mods.append([mod_id.strip().lower(), int(level) if level.strip() else 1])
        if mods:
            starting_card_mods.setdefault(general_id, {})[int(row['id'])] = mods

def dump(value):
    return json.dumps(value, indent=2)

js = """// GENERATED by scripts/roguelike_progression.py from roguelike_csv/account_progression.csv, general_progression.csv,
// progression_xp.csv and the `mods` column of roguelike_csv/generals/*.csv, do not edit by hand.
module.exports = {
  accountLevels: %s,
  generalLevels: %s,
  xp: %s,
  // general id -> card id -> [[mod id, hero level], ...]
  startingCardMods: %s,
};
""" % tuple(dump(value).replace('\n', '\n  ') for value in (account_levels, general_levels, xp, {str(k): {str(c): m for c, m in v.items()} for k, v in starting_card_mods.items()}))
open(OUT, 'w', encoding='utf-8', newline='\n').write(js)
print('%d account levels, %d general levels, %d generals with starting mods -> %s' % (len(account_levels), len(general_levels), len(starting_card_mods), OUT))
